    /** A ring centred on (cx,cy): outer disc wound ink, inner hole wound the other way to open it. */
    private fun ring(cx: Float, cy: Float, outer: Float, inner: Float): String {
        val o = String.format(Locale.ROOT, "%.2f,%.2f", outer, outer)
        val i = String.format(Locale.ROOT, "%.2f,%.2f", inner, inner)
        val oTop = String.format(Locale.ROOT, "%.2f,%.2f", cx, cy - outer)
        val oBot = String.format(Locale.ROOT, "%.2f,%.2f", cx, cy + outer)
        val iTop = String.format(Locale.ROOT, "%.2f,%.2f", cx, cy - inner)
        val iBot = String.format(Locale.ROOT, "%.2f,%.2f", cx, cy + inner)
        return "M$oTop A$o 0 1 1 $oBot A$o 0 1 1 $oTop Z " +
            "M$iTop A$i 0 1 0 $iBot A$i 0 1 0 $iTop Z"
    }

    /** A disc centred on (12,12) as two semicircle arcs: sweep 1 winds ink, sweep 0 winds a cut. */
    private fun disc12(radius: Float, ink: Boolean): String {
        val sweep = if (ink) 1 else 0
        val top = String.format(Locale.ROOT, "12,%.2f", 12.0 - radius)
        val bottom = String.format(Locale.ROOT, "12,%.2f", 12.0 + radius)
        val r = String.format(Locale.ROOT, "%.2f,%.2f", radius, radius)
        return "M$top A$r 0 1 $sweep $bottom A$r 0 1 $sweep $top Z "
    }

    /** A point on the (12,12) grid at `deg` degrees and `radius` units, as `x,y`. */
    private fun polar12(deg: Double, radius: Float): String {
        val a = Math.toRadians(deg)
        return String.format(
            Locale.ROOT, "%.2f,%.2f",
            12.0 + radius * Math.cos(a), 12.0 + radius * Math.sin(a),
        )
    }

    /**
     * A band of daylight between two spokes: from `rIn` to `rOut`, spanning `from`..`to` degrees.
     * The inner arc runs with the angle and the outer arc runs back against it, which is the way
     * round a cut has to go in this y-down grid, so a fill rule opens the face it sits in instead
     * of painting over it. Both arcs are under 180°, hence the 0 large-arc flag.
     */
    private fun opening12(from: Double, to: Double, rIn: Float, rOut: Float): String {
        val ri = String.format(Locale.ROOT, "%.2f,%.2f", rIn, rIn)
        val ro = String.format(Locale.ROOT, "%.2f,%.2f", rOut, rOut)
        return "M" + polar12(from, rIn) + " A$ri 0 0 1 " + polar12(to, rIn) +
            " L" + polar12(to, rOut) + " A$ro 0 0 0 " + polar12(from, rOut) + " Z "
    }
