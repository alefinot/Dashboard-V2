#!/usr/bin/env python3
"""Turn the settings group icons into Android vector drawables.

Each settings group's header badge is a lucide path held as `iconSVG` in
`scripts/config_schema_presentation.json` (it used to sit inline in the unit's web
page, which is deleted). The app shows the same badge on the accordion rows, and
Android wants a `VectorDrawable`, so the shapes are converted rather than retyped - a
hand-copied gear is a gear that quietly stops matching the schema's own name for it.

Run from the repo root:

    python scripts/icons_to_drawables.py

writes `android/app/src/main/res/drawable/ic_grp_<name>.xml` for every group named in
`GROUP_ICONS` below. `--check` exits non-zero if a written file no longer matches what
the presentation tree would produce today, the same way `gen_config_schema.py --check`
guards the schema asset. Only the *name* travels in `assets/config_schema.json`; the
drawing lives here, in the UI layer.

Three notes on the conversion, because lucide and Android are not the same dialect:

  * lucide draws with strokes (`fill="none"`, `stroke-width="2"`, round caps and joins).
    Those become `strokeColor` / `strokeWidth` / `strokeLineCap` on the path, and the
    path stays unfilled - filling it would turn a line drawing into a black blob.
  * `<circle>` and `<line>` have no VectorDrawable element that takes their attributes, so
    they are compiled into path data: a circle as two arcs, a line as one segment.
  * `<rect rx>` becomes the same rectangle with two arcs at each corner.
"""
import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRESENTATION = ROOT / "scripts" / "config_schema_presentation.json"
OUT_DIR = ROOT / "android" / "app" / "src" / "main" / "res" / "drawable"

# The groups `assets/config_schema.json` names, and the `iconSVG` key each one's badge
# comes from. `more` is the leftover bucket that `gen_config_schema.py` invents from
# unlabelled rows: the presentation tree has no icon for it, so it gets lucide's
# `more-horizontal`, which is the same shape nothing else uses and the only one
# that reads as "the rest of them".
GROUP_ICONS = {
    "system": "system",
    "display": "display",
    "sensors": "sensors",
    "layout": "layout",
}

MORE_HORIZONTAL = (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
    'stroke="currentColor" stroke-width="2" stroke-linecap="round" '
    'stroke-linejoin="round">'
    '<circle cx="12" cy="12" r="1"/><circle cx="19" cy="12" r="1"/>'
    '<circle cx="5" cy="12" r="1"/></svg>'
)

HEADER = (
    '<!-- Generated by scripts/icons_to_drawables.py from the iconSVG tree in\n'
    '     scripts/config_schema_presentation.json - do not edit by hand; re-run the\n'
    '     script instead.\n'
    '     Icon: {src} (lucide, ISC licence), stroke for stroke.\n'
    '-->'
)


def number(x):
    """Trim a float the way an SVG author would: 2.0 -> 2, 1.65 -> 1.65."""
    f = float(x)
    return str(int(f)) if f == int(f) else ("%g" % f)


def circle_path(cx, cy, r):
    """A circle as two half arcs, starting at the leftmost point."""
    cx, cy, r = number(cx), number(cy), number(r)
    return "M {0} {1} a {2} {2} 0 1 0 {3} 0 a {2} {2} 0 1 0 -{3} 0".format(
        number(float(cx) - float(r)), cy, r, number(2 * float(r))
    )


def rect_path(x, y, w, h, rx=0.0, ry=0.0):
    x, y, w, h = float(x), float(y), float(w), float(h)
    rx = float(rx or 0)
    ry = float(ry or rx)
    right, bottom = x + w, y + h
    if rx <= 0 or ry <= 0:
        return "M {0} {1} L {2} {1} L {2} {3} L {0} {3} Z".format(
            number(x), number(y), number(right), number(bottom)
        )
    # Clockwise from the end of the top-left corner, one arc per corner - the order an
    # SVG author writes a rounded rect in, which is the order a reader can check.
    arc = "{} {} 0 0 1".format(number(rx), number(ry))
    return (
        "M {0} {1} L {2} {1} a {arc} {3} {4} L {5} {6} a {arc} -{3} {4}"
        " L {7} {8} a {arc} -{3} -{4} L {9} {10} a {arc} {3} -{4} Z"
    ).format(
        # Clockwise: end of the top edge, right edge, bottom edge, left edge, and the
        # arc at each corner between them.
        number(x + rx), number(y), number(right - rx), number(rx), number(ry),
        number(right), number(bottom - ry), number(x + rx), number(bottom),
        number(x), number(y + ry), arc=arc,
    )


def paths_from(svg_text):
    """The drawing's paths as (pathData) pairs, plus the stroke settings."""
    root = ET.fromstring(svg_text)
    stroke = root.get("stroke", "currentColor")
    width = root.get("stroke-width", "2")
    cap = root.get("stroke-linecap", "round")
    join = root.get("stroke-linejoin", "round")
    out = []
    for el in root:
        # ET keeps the SVG namespace on the tag; the element names are what matter.
        tag = el.tag.split("}")[-1]
        if tag == "path":
            out.append(el.get("d"))
        elif tag == "circle":
            # A dot drawn with r=1 and a stroke of 2 reads as a filled dot; that is what
            # lucide means, and the arcs reproduce it exactly.
            out.append(circle_path(el.get("cx"), el.get("cy"), el.get("r")))
        elif tag == "line":
            out.append("M {0} {1} L {2} {3}".format(
                number(el.get("x1")), number(el.get("y1")),
                number(el.get("x2")), number(el.get("y2")),
            ))
        elif tag == "rect":
            out.append(rect_path(el.get("x"), el.get("y"), el.get("width"),
                                 el.get("height"), el.get("rx"), el.get("ry")))
        elif tag == "polyline":
            pts = el.get("points").replace(",", " ").split()
            body = " ".join(
                ("M " if i == 0 else " L ") + pts[i * 2] + " " + pts[i * 2 + 1]
                for i in range(len(pts) // 2)
            )
            out.append(body)
        else:
            raise SystemExit("unhandled lucide element <%s> - add it to the converter" % tag)
    return out, stroke, width, cap, join


def drawable(name, svg_text, source):
    paths, stroke, width, cap, join = paths_from(svg_text)
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        HEADER.format(src=source),
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp" android:height="24dp"',
        '    android:viewportWidth="24" android:viewportHeight="24"',
        '    android:tint="#FFFFFFFF">',
    ]
    for d in paths:
        lines.append(
            '    <path android:pathData="{0}" android:fillColor="#00000000"'.format(d)
        )
        lines.append(
            '        android:strokeColor="#FFFFFFFF" android:strokeWidth="{0}"'.format(width)
        )
        lines.append(
            '        android:strokeLineCap="{0}" android:strokeLineJoin="{1}" />'.format(
                "butt" if cap == "butt" else cap, "miter" if join == "miter" else join
            )
        )
    lines.append("</vector>")
    lines.append("")
    return "\n".join(lines)


def icon_block():
    """The `iconSVG` map from the settings presentation tree."""
    import json
    if not PRESENTATION.exists():
        raise SystemExit(
            "no %s - it carries the group icons alongside the labels and grouping"
            % PRESENTATION)
    icons = json.loads(PRESENTATION.read_text(encoding="utf-8")).get("iconSVG")
    if not isinstance(icons, dict) or not icons:
        raise SystemExit("%s has no usable iconSVG map" % PRESENTATION)
    return icons


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    icons = icon_block()
    wanted = {}
    for group, key in GROUP_ICONS.items():
        if key not in icons:
            raise SystemExit("iconSVG has no %r, which the schema names for group %r" % (key, group))
        wanted[group] = (icons[key], "iconSVG.%s" % key)
    wanted["more"] = (MORE_HORIZONTAL, "lucide more-horizontal (the presentation tree has no icon here)")

    stale = []
    for group, (svg, source) in wanted.items():
        path = OUT_DIR / ("ic_grp_%s.xml" % group)
        text = drawable(group, svg, source)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path))
        else:
            OUT_DIR.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print("wrote", path.relative_to(ROOT))
    if stale:
        print("out of date, re-run without --check:\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
